/** Flat skill names for Schema.org `skills` + accessible list */
export function allSkillNames(): string[] {
  const fromGroups = skills.groups.flatMap((g) => g.items.map((i) => i.name))
  return [...new Set([...fromGroups, ...skills.tools])]
}

/** Person + related SoftwareSourceCode graph for JSON-LD */
export function buildPersonJsonLd() {
  const skillNames = allSkillNames()
  const sameAs = [profile.github].filter(Boolean)

  const projectNodes = projects.map((p, i) => ({
    "@type": "SoftwareSourceCode" as const,
    "@id": `#project-${i + 1}`,
    name: p.title,
    description: p.description,
    programmingLanguage: p.programmingLanguage,
    runtimePlatform: "Android",
    ...(p.codeRepository ? { codeRepository: p.codeRepository } : {}),
  }))

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Person",
        "@id": "#person",
        name: profile.name,
        givenName: profile.givenName,
        familyName: profile.familyName,
        url: profile.url,
        jobTitle: profile.role,
        description: profile.description,
        image: profile.avatar,
        email: `mailto:${profile.email}`,
        telephone: profile.phoneHref.replace("tel:", ""),
        address: {
          "@type": "PostalAddress",
          addressLocality: "Yangon",
          addressRegion: "South Okkalapa",
          addressCountry: "MM",
        },
        workLocation: {
          "@type": "Place",
          name: profile.workLocation,
        },
        sameAs,
        knowsAbout: profile.knowsAbout,
        skills: skillNames,
        knowsLanguage: profile.languages.map((l) => l.code),
        alumniOf: education.map((ed) => ({
          "@type": "EducationalOrganization",
          name: ed.org,
        })),
        hasOccupation: {
          "@type": "Occupation",
          name: profile.role,
          occupationalCategory: "Software Developer",
          skills: skillNames.slice(0, 8),
        },
        subjectOf: projectNodes.map((n) => ({ "@id": n["@id"] })),
      },
      ...projectNodes,
    ],
  }
}
